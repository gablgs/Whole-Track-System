export function buildSeedWorkers(): Worker[] {
  const map = new Map<string, Worker>();
  SEED_SCHEDULE_ROWS.forEach((row, i) => {
    if (!map.has(row.name)) {
      map.set(row.name, {
        id: `w-${i + 1}`,
        name: row.name,
        phone: '',
        notes: '',
        preferredRoles: [row.role],
        shifts: []
      });
    }
    const worker = map.get(row.name)!;
    worker.shifts.push({
      id: `s-${i + 1}`,
      day: row.day,
      time: row.time,
      role: row.role,
      status: 'assigned'
    });
  });
  return Array.from(map.values());
}
